// 데이터셋 무결성 검사용 헬퍼: 모든 금지 패턴에 code/re/message가 있는지
export function listBannedHits(text) {
  const value = String(text || '');
  return BANNED_PATTERNS.filter((p) => p.re.test(value)).map((p) => ({ code: p.code, message: p.message }));
}
