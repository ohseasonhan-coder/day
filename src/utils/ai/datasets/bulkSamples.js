export function makeSamples(count) {
  const out = [];
  for (let i = 0; i < count; i++) {
    const name = NAMES[i % NAMES.length];
    const [category, tmpl] = SCENES[(i * 13) % SCENES.length];
    out.push({ category, text: tmpl(subj(name)), name });
  }
  return out;
}

