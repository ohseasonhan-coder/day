// 주격 조사: 받침 있으면 '이가', 없으면 '가' (예: 도윤→도윤이가, 지우→지우가)
function subj(name) {
  const last = name.charCodeAt(name.length - 1);
  const hasBatchim = last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 !== 0;
  return name + (hasBatchim ? '이가' : '가');
}

