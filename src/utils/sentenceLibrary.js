/** 카테고리 목록 */
export const CATEGORIES = Object.keys(LIBRARY);

/** 상황 목록 */
export const SITUATIONS = ['positive', 'growing', 'support'];

/**
 * 단일 문장 생성
 * @param {{category:string, situation:string, age:number, childName:string}} opts
 * @returns {string}
 */
export function generateSentence({ category, situation, age, childName }) {
  const cat = LIBRARY[category] || LIBRARY.peer;
  const sit = cat[situation] || cat.positive;

  const ctx    = pick(sit.contexts);
  const ageKey = `age${age}`;
  const pool   = sit.actions[ageKey] || sit.actions.common || [];
  const act    = pick(pool.length ? pool : sit.actions.common);
  const obs    = pick(TEACHER_OBS);
  const end    = pick(ENDINGS[situation] || ENDINGS.positive);

  return `${nameSubj(childName)} ${ctx} ${act} ${obs} ${end}`;
}

/**
 * 여러 문장 생성 (중복 최소화)
 * @param {{category:string, situation:string, age:number, childName:string, count:number}} opts
 * @returns {string[]}
 */
export function generateSentences({ category, situation, age, childName, count = 3 }) {
  const results = new Set();
  let tries = 0;
  while (results.size < count && tries < count * 10) {
    results.add(generateSentence({ category, situation, age, childName }));
    tries++;
  }
  return Array.from(results);
}

/**
 * 기록 내용을 분석하여 적합한 카테고리와 상황을 추정
 * @param {string} text 관찰 기록 텍스트
 * @returns {{category:string, situation:string}}
 */
export function detectCategoryFromText(text) {
  const t = text.toLowerCase();
  let category = 'peer';
  let situation = 'positive';

  // 카테고리 감지
  if (/친구|또래|사이좋|다툼|배려|사과|양보/.test(t)) category = 'peer';
  else if (/밥|식사|손씻|화장실|낮잠|정리|위생|양치/.test(t)) category = 'habit';
  else if (/말|발화|언어|표현|발음|이야기|대화|어휘/.test(t)) category = 'comm';
  else if (/놀이|탐구|블록|구성|과학|수학|탐색|만들기/.test(t)) category = 'play';
  else if (/자연|바깥|산책|씨앗|곤충|식물|날씨|환경/.test(t)) category = 'nature';
  else if (/미술|그리기|색칠|꾸미기|만들기|조형|재료/.test(t)) category = 'art';
  else if (/운동|달리기|몸|신체|체육|근육|균형|건강/.test(t)) category = 'body';

  // 상황 감지
  if (/어려움|지원|도움|걱정|개별|느린|지연|부족|힘들/.test(t)) situation = 'support';
  else if (/성장|조금|점차|연습|노력|발달|향상|개선/.test(t)) situation = 'growing';
  else if (/훌륭|잘|멋지|즐겁|적극|능숙|뛰어|칭찬|좋은/.test(t)) situation = 'positive';

  return { category, situation };
}

/**
 * 조합 가능한 총 문장 수 계산 (카테고리별)
 * @returns {{total:number, byCategory:Object}}
 */
export function calcCombinations() {
  const obs = TEACHER_OBS.length;
  let total = 0;
  const byCategory = {};

  for (const [catKey, catData] of Object.entries(LIBRARY)) {
    let catTotal = 0;
    for (const [sitKey, sitData] of Object.entries(catData)) {
      const ctxCount = sitData.contexts.length;
      const actKeys  = Object.keys(sitData.actions);
      const actTotal = actKeys.reduce((s, k) => s + sitData.actions[k].length, 0);
      const endCount = (ENDINGS[sitKey] || ENDINGS.positive).length;
      const sitCombos = ctxCount * actTotal * obs * endCount;
      catTotal += sitCombos;
    }
    byCategory[catKey] = catTotal;
    total += catTotal;
  }
  return { total, byCategory };
}
