function pick(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}
function nameSubj(name) {
  // 이름 + 이/가 조사
  const last = name.charCodeAt(name.length - 1);
  const hasFinal = (last - 0xAC00) % 28 !== 0;
  return name + (hasFinal ? '이' : '가');
}

