  // ㅆ받침 음절(했/갔/먹었/쌓았 등) + 음 → ~다  ("했음"→"했다", "있음"→"있다")
  // '마음', '웃음', '얼음' 같은 일반 명사는 앞 음절에 ㅆ받침이 없어 바뀌지 않는다
