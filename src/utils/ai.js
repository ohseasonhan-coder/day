// 따옴표 안 아이 발화는 원문 그대로 두고, 교사 서술 부분에만 변환 규칙을 적용한다
function applyOutsideQuotes(text, rules) {
  return text
    .split(/("[^"]*"|'[^']*')/g)
    .map((part, i) => {
      if (i % 2 === 1) return part;
      let result = part;
      for (const { pattern, replace } of rules) {
        result = result.replace(pattern, replace);
      }
      return result;
    })
    .join('');
}

function softenText(text) {
  return applyOutsideQuotes(normalizeRecordText(text), SOFTEN_MAP);
}

function applyPositiveRephrase(text) {
  return applyOutsideQuotes(text, POSITIVE_REPHRASE_MAP);
}

function hasFinalConsonant(value) {
  const last = [...String(value).trim()].pop();
  if (!last) return false;
  const code = last.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return false;
  return (code - 0xac00) % 28 !== 0;
}

function subject(name) {
  const clean = String(name || '아동').trim();
  // 이름이 받침으로 끝나면 '하준이가', 받침이 없으면 '윤재가'처럼 자연스럽게 붙인다.
  // 이미 '하준이'처럼 애칭형으로 저장된 이름은 '하준이가'로 처리한다.
  if (clean.endsWith('이')) return `${clean}가`;
  if (clean === '아동' || clean === '유아') return `${clean}이`;
  return `${clean}${hasFinalConsonant(clean) ? '이가' : '가'}`;
}

