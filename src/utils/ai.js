// 같은 입력엔 같은 결과, 다른 입력엔 다른 결과 — 문자 합 기반 결정적 선택
function hashPick(text, arr) {
  if (!arr.length) return '';
  let h = 0;
  const s = String(text || '');
  for (let i = 0; i < s.length; i++) h = (h + s.charCodeAt(i) * (i + 1)) % 100000;
  return arr[h % arr.length];
}

