function normalizeRecordText(text) {
  let result = String(text || '').normalize('NFC');
  result = result
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[，、]/g, ',')
    .replace(/[。]/g, '.')
    .replace(/[ㅋㅎㅠㅜ]{2,}/g, '')
    .replace(/(.)\1{3,}/g, '$1$1')
    .replace(/\s+/g, ' ')
    .trim();

  // 구어체 종결 변환은 맞춤법 규칙보다 먼저 — '말했어요'가 '말했다어요'로 깨지지 않도록
  result = convertSpokenEndings(result);

  for (const [pattern, replace] of TYPO_NORMALIZATION_RULES) {
    result = result.replace(pattern, replace);
  }
  for (const [pattern, replace] of PHRASE_NORMALIZATION_RULES) {
    result = result.replace(pattern, replace);
  }

  // 숫자+단위는 붙여쓰기 복원 ("37.8 도" → "37.8도")
  result = result.replace(/(\d)\s+(도|개|명|번|살|회|층|분|초)(?=[\s.,!?]|$)/g, '$1$2');

  // 목적격 조사 보정 — 흔한 '명사 + 동사' 짧은 입력에 빠진 을/를을 채운다 ("그림 그렸다" → "그림을 그렸다")
  for (const [pattern, replace] of OBJECT_PARTICLE_FIXES) {
    result = result.replace(pattern, replace);
  }

  return result.replace(/\s+/g, ' ').trim();
}

function cleanObservationInput(text) {
  const normalized = normalizeRecordText(text);
  return applyPositiveRephrase(softenText(normalized))
    .replace(/^\s*[가-힣A-Za-z0-9]+(?:이\/가|이\s*\/\s*가|이가|가|은|는)\s*/u, '')
    .replace(/\b([가-힣]+)이\/가\b/gu, '$1이가')
    .replace(/하였으며/g, '하고')
    .replace(/하였다/g, '하였다')
    .replace(/\s+/g, ' ')
    .replace(/잘기다린다/g, '차례를 기다리는 모습이 보였다')
    .replace(/잘 기다린다/g, '차례를 기다리는 모습이 보였다')
    .replace(/교사의 지원을 통해 상황을 경험하는 모습이 관찰되었다\.?/g, '')
    .replace(/교사의 지원을 통해 상황을 경험하는 모습이 보였다\.?/g, '')
    .replace(/교사의 안내를 통해 상황을 경험하였다\.?/g, '')
    .trim();
}

function finishSentence(text) {
  const clean = text
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.])/g, '$1')
    .replace(/[.。]+$/g, '');
  return clean ? `${clean}.` : '';
}

/* 문장·어절 경계를 지키며 자르기 — 입력 내용이 단어 중간에서 잘려나가지 않도록 */
function smartTruncate(text, limit = 110) {
  if (text.length <= limit) return text;
  const slice = text.slice(0, limit);
  const lastSentenceEnd = Math.max(slice.lastIndexOf('. '), slice.lastIndexOf('! '), slice.lastIndexOf('? '));
  if (lastSentenceEnd >= 30) return slice.slice(0, lastSentenceEnd + 1).trim();
  const lastSpace = slice.lastIndexOf(' ');
  return (lastSpace >= 30 ? slice.slice(0, lastSpace) : slice).trim();
}

function observationDetail(text, limit = 110) {
  const clean = cleanObservationInput(text);
  if (!clean) return '상황에 참여하며 경험을 이어가는 모습이 관찰되었다';
  const trimmed = smartTruncate(clean, limit).replace(/[.。!?]+$/u, '');
  // 끝맺음 변환은 행위 동사에만 — 형용사·교사 행동(기특했다, 칭찬했다 등)은 원문 유지
  return trimmed
    .replace(/말했다$/u, '말하는 모습이 관찰되었다')
    .replace(/(시도|참여|표현|사용|관찰|탐색|반복|연습|조작|구성|완성|시작|대답|요청|정리)(했다|하였다)$/u, '$1하는 모습이 관찰되었다')
    .replace(/기다렸다$/u, '기다리는 모습이 관찰되었다');
}

// 명사형·구어체 종결을 문어체 과거 서술로 (전체 일화기록 변환용)
const NARRATIVE_RULES = [
  [/해\s*버림(?=[\s.,!?"]|$)/g, '하였다'],
  [/([가-힣])아\s*버림(?=[\s.,!?"]|$)/g, '$1았다'],
  [/([가-힣])어\s*버림(?=[\s.,!?"]|$)/g, '$1었다'],
  [/([가-힣])줌(?=[\s.,!?"]|$)/g, '$1주었다'],
  [/이야기를\s*함(?=[\s.,!?"]|$)/g, '이야기하였다'],
  [/제안을\s*함(?=[\s.,!?"]|$)/g, '제안하였다'],
  [/따라\s*함(?=[\s.,!?"]|$)/g, '따라 하였다'],
  [/하지\s*않음(?=[\s.,!?"]|$)/g, '하지 않았다'],
  [/않음(?=[\s.,!?"]|$)/g, '않았다'],
  [/함(?=[\s.,!?"]|$)/g, '하였다'],
  [/했음(?=[\s.,!?"]|$)/g, '하였다'],
  [/([가-힣])됨(?=[\s.,!?"]|$)/g, '$1되었다'],
  // 해요체 잔여 정리
  [/했어요(?=[\s.,!?"]|$)/g, '하였다'],
  // 관찰일지 표준 용어
  [/선생님/g, '교사'],
];

// 관찰일지 = 입력 전체를 문어체 일화기록으로 (자르지 않음, 가짜 프레임 없음 — 사실 충실도 최우선)
function buildFaithfulObservation(name, normalizedText) {
  let t = String(normalizedText || '');
  // 종결 변환은 따옴표 밖에서만 (아이·교사 발화는 원문 보존)
  t = applyOutsideQuotes(t, NARRATIVE_RULES.map(([pattern, replace]) => ({ pattern, replace })));
  // 런온 문장 분리도 따옴표 밖에서만: '~였다 친구가' → '~였다. 친구가'
  t = applyOutsideQuotes(t, [{ pattern: /([았었였])다\s+(?=[가-힣"“])/g, replace: '$1다. ' }]);
  t = t.replace(/\s+/g, ' ').replace(/\s+([,.!?])/g, '$1').replace(/([.!?])\1+/g, '$1').trim();
  // 인용부호 앞 공백 정리: '싶어요? "라고' → '싶어요?"라고'
  t = t.replace(/([?!.])\s+"(\s*)(라고|하며|라며|라는|하고|하면서|이라고)/g, '$1"$3');
  if (!t) return '';

  const bare = String(name || '').trim();
  const hasName = bare && t.includes(bare);
  const isFullNarrative = t.length > 24 || /친구|또래|교사|선생/.test(t);
  if (!hasName && !isFullNarrative) {
    t = `${subject(name)} ${stripLeadingName(t, name)}`.replace(/\s+/g, ' ').trim();
  }

  // 마지막에 종결부호가 없으면 마침표 추가
  if (!/[.!?]["”']?$/.test(t)) t += '.';
  return t;
}

